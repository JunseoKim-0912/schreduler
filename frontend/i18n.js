const WEEKDAYS = {
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
  ko: ["일", "월", "화", "수", "목", "금", "토"],
};
const MONTHS_EN = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const BYDAY_INDEX = { SU: 0, MO: 1, TU: 2, WE: 3, TH: 4, FR: 5, SA: 6 };

function readSaved() {
  try {
    const saved = globalThis.localStorage?.getItem(LANG_KEY);
    return LANGUAGES.includes(saved) ? saved : null;
  } catch {
    return null;
  }
}

let current = readSaved() ?? DEFAULT_LANGUAGE;
const listeners = new Set();

export function getLang() {
  return current;
}

// 처음 방문인지(저장된 선택이 없는지). app.js가 이때도 백엔드 언어를 화면 언어(en)로 맞춘다.
export function hasSavedLang() {
  return readSaved() !== null;
}

export function setLang(lang) {
  if (!LANGUAGES.includes(lang)) return false;
  current = lang;
  try {
    globalThis.localStorage?.setItem(LANG_KEY, lang);
  } catch {
    // 저장소를 못 쓰면 이번 화면에서만 바뀐다.
  }
  for (const listener of listeners) listener(lang);
  return true;
}

export function onLangChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

// 키 → 지금 언어의 문구. {name} 자리를 params로 채운다. 지금 언어에 없으면 영어, 그래도 없으면 키 자체.
export function t(key, params = {}) {
  const template = MESSAGES[current]?.[key] ?? MESSAGES.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function hasMessage(key) {
  return key in MESSAGES[current] || key in MESSAGES.en;
}

export function messageKeys(lang) {
  return Object.keys(MESSAGES[lang]);
}

// --- 날짜 표기 ---------------------------------------------------------------------------------

export function weekdayName(dayIndex) {
  return WEEKDAYS[current][dayIndex];
}

export function bydayName(code) {
  const index = BYDAY_INDEX[code];
  return index === undefined ? code : WEEKDAYS[current][index];
}

// "Oct 6" / "10/6"
export function monthDay(month, day) {
  return current === "en" ? `${MONTHS_EN[month - 1]} ${day}` : `${month}/${day}`;
}

// "Oct 6 (Tue)" / "10/6 (화)"
export function monthDayWeekday(month, day, weekdayIndex) {
  return `${monthDay(month, day)} (${weekdayName(weekdayIndex)})`;
}

// 캘린더 머리 제목: "Sep 28 – Oct 4, 2026" / "2026년 9월 28일 – 10월 4일"
export function dateRangeTitle(first, last) {
  const [y1, m1, d1] = [first.getFullYear(), first.getMonth() + 1, first.getDate()];
  const [y2, m2, d2] = [last.getFullYear(), last.getMonth() + 1, last.getDate()];
  const single = first.getTime() === last.getTime();
  if (current === "en") {
    const a = `${MONTHS_EN[m1 - 1]} ${d1}`;
    if (single) return `${weekdayName(first.getDay())}, ${a}, ${y1}`;
    if (y1 !== y2) return `${a}, ${y1} – ${MONTHS_EN[m2 - 1]} ${d2}, ${y2}`;
    if (m1 !== m2) return `${a} – ${MONTHS_EN[m2 - 1]} ${d2}, ${y1}`;
    return `${a} – ${d2}, ${y1}`;
  }
  if (single) return `${y1}년 ${m1}월 ${d1}일 (${weekdayName(first.getDay())})`;
  if (y1 !== y2) return `${y1}년 ${m1}월 ${d1}일 – ${y2}년 ${m2}월 ${d2}일`;
  if (m1 !== m2) return `${y1}년 ${m1}월 ${d1}일 – ${m2}월 ${d2}일`;
  return `${y1}년 ${m1}월 ${d1}일 – ${d2}일`;
}

// 어시스턴트 입력창에 미리 채울 날짜: "Oct 6" / "10월 6일"
export function prefillDate(month, day) {
  return current === "en" ? `${MONTHS_EN[month - 1]} ${day}` : `${month}월 ${day}일`;
}

export function numberLocale() {
  return current === "en" ? "en-US" : "ko-KR";
}
